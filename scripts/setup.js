/**
 * "21:00" or "08:00, 21:30" -> cron expression. Times with different minutes
 * can't share one cron line, so those return null.
 */
function timesToCron(input) {
  const times = input.split(',').map((t) => t.trim()).filter(Boolean);
  if (!times.length) return null;
  const parsed = times.map((t) => /^(\d{1,2}):(\d{2})$/.exec(t));
  if (parsed.some((m) => !m || Number(m[1]) > 23 || Number(m[2]) > 59)) return null;
  const minutes = new Set(parsed.map((m) => Number(m[2])));
  if (minutes.size !== 1) return null;
  const hours = [...new Set(parsed.map((m) => Number(m[1])))].sort((a, b) => a - b);
  return `${[...minutes][0]} ${hours.join(',')} * * *`;
}

/** Builds the .env text from the answers. */
function buildEnv(a) {
  const lines = [
    '# Generated by `npm run setup`. Keep this file private (chmod 600).',
    '# Every option is explained in .env.example and README.md.',
    '',
    `# AI provider: ${a.providerName}`,
    `AI_URL=${a.aiUrl}`,
    `AI_KEY=${a.aiKey}`,
    `AI_MODEL=${a.aiModel}`,
    `CHUNK_SIZE=${a.chunkSize}`,
    `CHUNK_WAIT=${a.chunkWait}`,
    '',
    '# How to report: schedule | realtime | both',
    `MODE=${a.mode}`,
    `SCHEDULE=${a.schedule}`,
    `TIMEZONE=${a.timezone}`,
    `DELIVER_TO_WHATSAPP=${a.deliver}`,
  ];
  if (a.quietHours) lines.push(`QUIET_HOURS=${a.quietHours}`);
  lines.push('');
  if (a.urgentKeywords) lines.push('# Instant alerts', `URGENT_KEYWORDS=${a.urgentKeywords}`, '');
  if (a.encryptionKey) {
    lines.push('# Data files are encrypted with this key. Losing it means losing the data files.');
    lines.push(`DATA_ENCRYPTION_KEY=${a.encryptionKey}`, '');
  }
  lines.push('# HTTP API');
  lines.push(`API_ENABLED=${Boolean(a.apiKey)}`);
  if (a.apiKey) {
    lines.push(`API_HOST=${a.apiHost}`, `API_PORT=${a.apiPort}`, `API_KEYS=${a.apiKey}`);
  }
  lines.push('');
  if (a.webhookUrl) {
    lines.push('# Webhook (signed with WEBHOOK_SECRET)', `WEBHOOK_URL=${a.webhookUrl}`, `WEBHOOK_SECRET=${a.webhookSecret}`, '');
  }
  return lines.join('\n');
}

/**
 * Line reader that queues input, so answers piped in all at once
 * (e.g. from a script) are not lost.
 */
function createPrompter() {
  const rl = readline.createInterface({ input: process.stdin, terminal: false });
  const lines = [];
  const waiting = [];
  let ended = false;
  rl.on('line', (line) => (waiting.length ? waiting.shift()(line) : lines.push(line)));
  rl.on('close', () => {
    ended = true;
    while (waiting.length) waiting.shift()(null);
  });
  const nextLine = () =>
    lines.length ? Promise.resolve(lines.shift()) : ended ? Promise.resolve(null) : new Promise((r) => waiting.push(r));
  return {
    async question(prompt) {
      process.stdout.write(prompt);
      const line = await nextLine();
      if (line === null) throw new Error('\nInput ended before setup finished. Nothing was written.');
      if (!process.stdin.isTTY) process.stdout.write('\n');
      return line;
    },
    close: () => rl.close(),
  };
}

async function main() {
  const rl = createPrompter();
  const ask = async (q, def = '') => {
    const answer = (await rl.question(def !== '' ? `${q} [${def}]: ` : `${q}: `)).trim();
    return answer || String(def);
  };
  const yes = async (q, def = true) => /^y/i.test(await ask(`${q} (y/n)`, def ? 'y' : 'n'));

  console.log('\n=== AI WhatsApp Group Summarizer — setup ===\n');

  if (fs.existsSync(ENV_FILE)) {
    if (!(await yes('.env already exists. Replace it? (a backup is kept)', false))) {
      rl.close();
      return;
    }
    const backup = `${ENV_FILE}.bak-${Date.now()}`;
    fs.copyFileSync(ENV_FILE, backup);
    fs.chmodSync(backup, 0o600);
    console.log(`Backup saved to ${path.basename(backup)}\n`);
  }

  console.log('AI provider:');
  for (const [n, p] of Object.entries(PROVIDERS)) console.log(`  ${n}) ${p.name}`);
  let choice = await ask('Choose', '1');
  while (!PROVIDERS[choice]) choice = await ask('Choose 1-4', '1');
  const p = PROVIDERS[choice];

  const aiUrl = p.url || (await ask('Chat completions URL (…/v1/chat/completions)'));
  let aiKey = p.key || '';
  if (!aiKey) {
    if (p.keyHint) console.log(`  Get a key from: ${p.keyHint}`);
    while (!aiKey) aiKey = await ask('API key');
  }
  let aiModel = '';
  while (!aiModel) aiModel = await ask(choice === '2' ? 'Model name (ends with :free)' : 'Model name', p.model);

  console.log('\nHow should the bot tell you about new messages?');
  console.log('  1) schedule  — one summary at fixed times');
  console.log('  2) realtime  — an alert as soon as something important appears');
  console.log('  3) both      — real-time alerts plus the scheduled summary');
  const modes = { 1: 'schedule', 2: 'realtime', 3: 'both' };
  let modeChoice = await ask('Choose', '1');
  while (!modes[modeChoice]) modeChoice = await ask('Choose 1-3', '1');
  const mode = modes[modeChoice];

  let schedule = null;
  while (!schedule) {
    const t = await ask('Summary time(s), 24h, e.g. 21:00 or 08:00,21:00', '21:00');
    schedule = timesToCron(t);
    if (!schedule) console.log('  Use HH:MM, and the same minutes for every time (08:00,21:00 works; 08:15,21:00 does not).');
  }
  const detectedTz = Intl.DateTimeFormat().resolvedOptions().timeZone;
  const timezone = await ask('Time zone', detectedTz && detectedTz !== 'UTC' ? detectedTz : 'Africa/Cairo');
  let quietHours = '';
  if (mode !== 'schedule') {
    quietHours = await ask('Quiet hours for alerts, e.g. 23:00-07:00 (empty = none)', '');
    while (quietHours && !parseQuietHours(quietHours)) quietHours = await ask('Use HH:MM-HH:MM (empty = none)', '');
  }
  const deliver = await yes('Send summaries and alerts to your WhatsApp "Message yourself" chat?', true);
  const urgentKeywords = await ask('Instant alert words, comma-separated (empty = off)', '');

  console.log('\nSecurity');
  const encrypt = await yes('Encrypt stored messages and summaries on disk?', true);

  console.log('\nConnect other projects');
  const enableApi = await yes('Enable the HTTP API?', true);
  let apiHost = '127.0.0.1';
  let apiPort = 3000;
  if (enableApi) {
    console.log('  127.0.0.1 = only this machine (use a reverse proxy with HTTPS to expose it).');
    console.log('  0.0.0.0   = all network interfaces (needed inside Docker).');
    apiHost = await ask('  Listen address', apiHost);
    apiPort = Number(await ask('  Port', apiPort)) || 3000;
  }
  const webhookUrl = await ask('Webhook URL to push each new summary to (https://…, empty = none)', '');

  rl.close();

  const answers = {
    providerName: p.name,
    aiUrl,
    aiKey,
    aiModel,
    chunkSize: p.chunkSize,
    chunkWait: p.chunkWait,
    mode,
    schedule,
    timezone,
    quietHours,
    deliver,
    urgentKeywords,
    encryptionKey: encrypt ? randomSecret() : '',
    apiKey: enableApi ? randomSecret() : '',
    apiHost,
    apiPort,
    webhookUrl,
    webhookSecret: webhookUrl ? randomSecret() : '',
  };

  fs.writeFileSync(ENV_FILE, buildEnv(answers), { mode: 0o600 });
  fs.chmodSync(ENV_FILE, 0o600);

  console.log('\n✅ Saved .env (only your user can read it).\n');
  if (answers.apiKey || answers.webhookSecret) {
    console.log('=== Credentials for your other project (also stored in .env) ===');
    if (answers.apiKey) {
      console.log(`API base URL : http://${apiHost === '0.0.0.0' ? '<server-ip>' : apiHost}:${apiPort}`);
      console.log(`API key      : ${answers.apiKey}`);
      console.log('Header       : Authorization: Bearer <API key>');
    }
    if (answers.webhookSecret) console.log(`Webhook secret: ${answers.webhookSecret}`);
    console.log('Keep these secret. Docs: docs/API.md\n');
  }
  if (answers.encryptionKey) {
    console.log('⚠️  Back up DATA_ENCRYPTION_KEY from .env somewhere safe. Without it the data files cannot be read.\n');
  }
  console.log('Next: npm start  → scan the QR code → send !جروبات then !تابع <number> in "Message yourself".');
}

if (require.main === module) {
  main().catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}

module.exports = { timesToCron, buildEnv };
